"""What a built site needs on OVH's web hosting (Apache, shared): its .htaccess, a 404 page and security.txt. Called by
site/build.py once both sites are built, so the Content-Security-Policy carries the hashes of the inline scripts the
pages really have.

OVH's shared Apache honours .htaccess with mod_rewrite (« Réécrire l'URL d'accès à mon site grâce au mod_rewrite »,
which redirects to HTTPS with `RewriteCond %{SERVER_PORT} 80`) and mod_headers (« Hébergement web - Activer le CDN »,
which sets Cache-Control with `Header set`), both on docs.ovhcloud.com; ErrorDocument is in « Les autres opérations
réalisables avec un fichier .htaccess ». Every block is still wrapped in <IfModule> so a missing module never turns the
site into a 500.
"""
from __future__ import annotations

import base64
import hashlib
import html
import re
from pathlib import Path
from typing import Dict, List

# HSTS starts short (5 minutes) while the certificates settle; raise it to a year (31536000) once https has worked for
# a few days on both domains, then think about includeSubDomains (guichet.bipagents.com, the relay…).
HSTS_MAX_AGE = 300

INLINE_SCRIPT = re.compile(r"<script(?P<attrs>[^>]*)>(?P<body>.*?)</script>", re.S | re.I)


def inline_script_hashes(site: Path) -> List[str]:
    """The sha256 of every inline script that runs (JSON data blocks don't), across the site's HTML files."""
    found = set()
    for page in sorted(site.rglob("*.html")):
        for match in INLINE_SCRIPT.finditer(page.read_text(encoding="utf-8")):
            attrs = match.group("attrs").lower()
            if "src=" in attrs or re.search(r"type=[\"']?application/(ld\+)?json", attrs):
                continue
            digest = hashlib.sha256(match.group("body").encode("utf-8")).digest()
            found.add("'sha256-" + base64.b64encode(digest).decode() + "'")
    return sorted(found)


def csp(site: Path) -> str:
    """No third party at all: scripts from the site (plus its own inline ones, by hash), styles from the site (inline
    style attributes and <style> blocks are used, hence 'unsafe-inline' for styles only), the demo's pages framed from
    the site itself, forms and links free to leave (the checkout is a link to the guichet, not a form)."""
    scripts = " ".join(["'self'"] + inline_script_hashes(site))
    return "; ".join([
        "default-src 'self'",
        f"script-src {scripts}",
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data:",
        "font-src 'self'",
        "media-src 'self'",
        "connect-src 'self'",
        "frame-src 'self'",
        "worker-src 'self'",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'self'",
        "frame-ancestors 'self'",
        "upgrade-insecure-requests",
    ])


def htaccess(site: Path, domain: str) -> str:
    apex = re.escape(domain)
    return f"""# Generated by site/build.py (site/hosting.py) for OVH's web hosting: don't edit here, it's rebuilt each time.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset utf-8
<IfModule mod_mime.c>
  AddType application/json .json
  AddType audio/mp4 .m4a
  AddType font/ttf .ttf
  AddType image/svg+xml .svg
  AddType text/plain .txt
  AddCharset utf-8 .html .css .js .json .txt .svg .xml
</IfModule>
# The universal links file has no extension; Apple wants it as JSON, without redirect.
<Files "apple-app-site-association">
  ForceType application/json
</Files>

# One hop to https://{domain}/: http → https and www.{domain} → {domain} (OVH's own rule tests the port).
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteCond %{{HTTP_HOST}} !^{apex}$ [NC,OR]
  RewriteCond %{{SERVER_PORT}} ^80$
  RewriteRule ^ https://{domain}%{{REQUEST_URI}} [R=301,L]
  # Stylesheets and scripts asked with ?v=<build> never change under that address.
  RewriteCond %{{QUERY_STRING}} (^|&)v=[0-9]+(&|$)
  RewriteRule \\.(css|js)$ - [E=VERSIONED:1]
</IfModule>

<IfModule mod_headers.c>
  Header always set Strict-Transport-Security "max-age={HSTS_MAX_AGE}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
  Header always set Content-Security-Policy "{csp(site)}"
  # Pages, data and the well-known files: always asked again (cheap: Apache answers 304 when unchanged).
  <FilesMatch "\\.(html|json|txt|xml)$|^apple-app-site-association$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  # Stylesheets and scripts: a year when versioned (?v=), else asked again (bips.js is imported without version).
  <FilesMatch "\\.(css|js)$">
    Header set Cache-Control "no-cache"
    Header set Cache-Control "public, max-age=31536000, immutable" env=VERSIONED
    Header set Cache-Control "public, max-age=31536000, immutable" env=REDIRECT_VERSIONED
  </FilesMatch>
  # Fonts, pictures, recordings: not versioned by name, so a week.
  <FilesMatch "\\.(png|jpe?g|webp|gif|svg|ico|ttf|woff2?|m4a|mp3)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>
"""


NOT_FOUND = {
    "bipagents.com": ("en", "Page not found · BipAgents", "This page doesn't exist.",
                      "It may have moved. The home page has everything:", "BipAgents",
                      [("/", "English"), ("/fr/", "Français"), ("/de/", "Deutsch"), ("/es/", "Español")]),
    "kerfystudio.com": ("fr", "Page introuvable · Kerfy Studio", "Cette page n'existe pas.",
                        "Elle a peut-être changé d'adresse. Tout part de l'accueil :", "Kerfy Studio",
                        [("/", "Français"), ("/en/", "English"), ("/de/", "Deutsch"), ("/es/", "Español")]),
}


def not_found(domain: str) -> str:
    """A small page of its own (no script, the site's font), shown by Apache for any missing address."""
    lang, title, heading, text, name, links = NOT_FOUND[domain]
    items = " · ".join(f'<a href="{href}">{html.escape(label)}</a>' for href, label in links)
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>{html.escape(title)}</title>
<link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
<style>
@font-face {{ font-family: Nunito; src: url("/assets/nunito.ttf"); font-weight: 200 1000; }}
:root {{ color-scheme: light dark; --bg: #fffaf5; --ink: #1d1b22; --muted: #5d5866; --accent: #c9472a; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg: #17151b; --ink: #f4f1f7; --muted: #b4aebd; --accent: #ff9a80; }} }}
body {{ margin: 0; min-height: 100vh; display: grid; place-items: center; background: var(--bg); color: var(--ink);
       font: 18px/1.5 Nunito, system-ui, sans-serif; padding: 0 16px; box-sizing: border-box; }}
main {{ max-width: 34rem; }}
h1 {{ font-size: 2rem; margin: 0 0 .5rem; }}
p {{ color: var(--muted); }}
a {{ color: var(--accent); font-weight: 700; }}
</style>
</head>
<body>
<main>
<p>{html.escape(name)} · 404</p>
<h1>{html.escape(heading)}</h1>
<p>{html.escape(text)}</p>
<p>{items}</p>
</main>
</body>
</html>
"""


def security_txt(domain: str, contact: Dict[str, str], policy: str) -> str:
    """RFC 9116; the same contact on both sites, each with its own canonical address."""
    return (f"Contact: mailto:{contact['security']}\nExpires: 2027-10-01T00:00:00.000Z\nPreferred-Languages: fr, en\n"
            f"Canonical: https://{domain}/.well-known/security.txt\nPolicy: {policy}\n")


def finish(site: Path, domain: str, cfg: Dict) -> None:
    """Called last: the 404 page and security.txt first (the hashes see every page), then the .htaccess."""
    (site / "404.html").write_text(not_found(domain), encoding="utf-8")
    well_known = site / ".well-known"
    well_known.mkdir(exist_ok=True)
    policy = cfg.get("repo", "https://github.com/Alexbob0/BipAgents").rstrip("/") + "/blob/main/SECURITY.md"
    (well_known / "security.txt").write_text(security_txt(domain, cfg["contact"], policy), encoding="utf-8")
    (site / ".htaccess").write_text(htaccess(site, domain), encoding="utf-8")
