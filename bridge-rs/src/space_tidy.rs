//! Each agent's working space tidied by itself (Alex, 2026-11-07: agents in other bot apps never clean up after
//! themselves, « il faut une règle pour nos agents dans BipAgents »). Two halves:
//!
//! - **the rule** in every agent's personality (souls.rs `TIDY_RULE`): at the end of a task, delete the working files
//!   it made and no longer needs, keep the result and what the person asked to keep, never touch the person's own
//!   files; a sandboxed agent is told where its drafts go (`/workspace/brouillons`, sandbox.rs) and a background task
//!   gets a folder of its own there (`/workspace/brouillons/<task id>`, jobs.rs);
//! - **this pass**, every `every_hours` (6), which removes what is temporary by nature once it is old enough, so an
//!   agent that forgot (or a model that never tidies) leaves nothing behind for long.
//!
//! **Temporary** (the whole list; nothing else is ever removed here):
//!
//! - an entry of the agent's drafts folder, `/workspace/brouillons` (each of its Hermes sandboxes:
//!   `<profile>/sandboxes/docker/<key>/workspace/brouillons`), with no change anywhere inside it for `scratch_days`
//!   (7);
//! - a background task's own folder there (`brouillons/t<12 hex>`, its job id): once the task is over (done or failed)
//!   and nothing changed inside it for `task_hours` (24) since; a task the person forgot: `task_hours` after its last
//!   change. Never while the task waits, runs or is paused (it may go on);
//! - what its visible browser downloaded (`/telechargements`, browsers.rs): older than `DOWNLOADS_KEPT_DAYS` (30, what
//!   the agent was told), a download that never finished (`.crdownload`) after a day. What it handed over has its own
//!   copy already (sent_files.rs, give_file.rs, service_files.rs, the Archives);
//! - the package caches of its sandbox (`/root/.cache/pip`, `uv`, `yarn`, `/root/.npm/_cacache`): no change inside for
//!   `cache_days` (14); pip and npm fetch again what they need.
//!
//! « No change » is the newest of the modification and status-change times of the entry and everything inside it:
//! a file just unpacked or copied with its old date counts from its arrival.
//!
//! **Never**: the files the person sent (uploads, `/fichiers`: their own retention, files_kept.rs), what was given to
//! them (sent_files.rs' copies, pages, audio, maps: their own rules, storage_watch.rs), the Archives, shared folders,
//! `/envoi`, the rest of `/workspace` and `/root`, the browser's profile (logins), memory, the Carnet, conversations.
//! Every name is reached from an open folder without following a link (beneath.rs): a sandbox that swaps its drafts
//! folder for a link to the person's files gets nothing removed. When unsure (a folder too deep, an error), kept.
//!
//! What the person sees: nothing, unless one pass freed at least `line_mb` (200) of an agent's space: then one quiet
//! line in that agent's Boîte, no push, at most once a week (« J'ai fait le ménage dans mon espace de travail : 320 Mo
//! de fichiers temporaires effacés. Tes fichiers n'ont pas bougé. »). Each pass that removed something is logged
//! (`bipbridge::space_tidy`: by agent and kind, counts and bytes, never a file's name) and kept in
//! `<data>/space-tidy.json` (the last 100).
//!
//!     [tidy]   enabled = true, every_hours = 6, scratch_days = 7, task_hours = 24, cache_days = 14, line_mb = 200
//!
//! No Python counterpart.

