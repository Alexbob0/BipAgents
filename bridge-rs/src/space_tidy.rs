    #[test]
    fn never_through_a_link() {
        let p = place();
        // the person's file, somewhere a sandbox should never reach
        let theirs = p.root.join("theirs");
        std::fs::create_dir_all(&theirs).unwrap();
        std::fs::write(theirs.join("photo.jpg"), b"jpg").unwrap();
        // the drafts folder swapped for a link to it: nothing removed there
        std::fs::create_dir_all(p.sandbox().join("workspace")).unwrap();
        std::os::unix::fs::symlink(&theirs, p.sandbox().join("workspace/brouillons")).unwrap();
        assert!(pass(&p.config, days(400.0)).is_empty());
        assert!(theirs.join("photo.jpg").exists());
        // a link inside the drafts: the link goes, never what it leads to
        std::fs::remove_file(p.sandbox().join("workspace/brouillons")).unwrap();
        std::fs::create_dir_all(p.sandbox().join("workspace/brouillons/vieux")).unwrap();
        std::os::unix::fs::symlink(&theirs, p.sandbox().join("workspace/brouillons/lien")).unwrap();
        std::os::unix::fs::symlink(&theirs, p.sandbox().join("workspace/brouillons/vieux/lien")).unwrap();
        let freed = pass(&p.config, days(8.0));
        assert_eq!(freed[0].kinds["drafts"].0, 2);
        assert!(theirs.join("photo.jpg").exists());
        // a cache reached through a link on the way: kept
        std::fs::create_dir_all(p.sandbox().join("home")).unwrap();
        std::os::unix::fs::symlink(&theirs, p.sandbox().join("home/.cache")).unwrap();
        assert!(pass(&p.config, days(400.0)).is_empty());
        assert!(theirs.join("photo.jpg").exists());
    }

