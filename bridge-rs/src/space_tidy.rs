    #[test]
    fn a_big_pass_writes_one_quiet_line_a_week_and_keeps_its_record() {
        let mut p = place();
        p.config.tidy.line_mb = 0.001; // 1 KB
        p.write("workspace/brouillons/a.bin", 2000);
        assert_eq!(run_once(&p.config, days(8.0)), vec![("vie".to_string(), 2000)]);
        // two days later: removed, but told this week already
        p.write("workspace/brouillons/b.bin", 2000);
        assert!(run_once(&p.config, days(10.0)).is_empty());
        // more than a week after the first line: a line again
        p.write("workspace/brouillons/c.bin", 2000);
        assert_eq!(run_once(&p.config, days(16.0)), vec![("vie".to_string(), 2000)]);
        // under the threshold: removed, no line
        p.config.tidy.line_mb = 1.0;
        p.write("workspace/brouillons/d.bin", 2000);
        assert!(run_once(&p.config, days(40.0)).is_empty());
        assert!(!p.sandbox().join("workspace/brouillons/d.bin").exists());
        // nothing to remove: nothing kept either
        assert!(run_once(&p.config, days(41.0)).is_empty());
        let store = load(&p.config);
        assert_eq!(store.history.len(), 4);
        assert_eq!(store.history[0].kinds["drafts"], (1, 2000));
        let mode = std::fs::metadata(store_path(&p.config)).unwrap().permissions();
        assert_eq!(std::os::unix::fs::PermissionsExt::mode(&mode) & 0o777, 0o600);
    }

