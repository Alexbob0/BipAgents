"""Writes src/voice_speech/pychars.rs: Python's character classes (``\\w``, ``\\d``, ``\\s`` of ``re`` and
``str.isdigit``/``isupper``), as range tables, so the Rust text processing matches Python's on every character.

Run from bridge/ with the bridge's venv:
    python ../bridge-rs/tests/golden/gen_pychars.py
"""
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "voice_speech", "pychars.rs")


def ranges(predicate):
    out = []
    start = None
    for cp in range(sys.maxunicode + 2):
        inside = cp <= sys.maxunicode and predicate(chr(cp))
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


WORD = re.compile(r"\w")
DECIMAL = re.compile(r"\d")
SPACE = re.compile(r"\s")

tables = {
    "WORD": ("`re`'s `\\w`: `str.isalnum()` or `_`.", ranges(lambda c: WORD.match(c) is not None)),
    "DECIMAL": ("`re`'s `\\d`: `str.isdecimal()` (what `int()` reads).", ranges(lambda c: DECIMAL.match(c) is not None)),
    "SPACE": ("`re`'s `\\s`: `str.isspace()` (what `strip()` and `split()` remove).",
              ranges(lambda c: SPACE.match(c) is not None)),
    "DIGIT": ("`str.isdigit()` (superscripts included).", ranges(str.isdigit)),
    "UPPER": ("`str.isupper()` of one character.", ranges(str.isupper)),
}

# Decimal digits come in runs of ten from their zero (checked here): a digit's value is its distance from the zero
# of its run.
zeros = [cp for cp in range(sys.maxunicode + 1) if chr(cp).isdecimal() and unicodedata.decimal(chr(cp)) == 0]
assert all(unicodedata.decimal(chr(z + i)) == i for z in zeros for i in range(10))

lines = [
    "//! Python's character classes (generated by `tests/golden/gen_pychars.py` from Python "
    f"{sys.version_info.major}.{sys.version_info.minor}, Unicode {unicodedata.unidata_version}): `re`'s `\\w`, `\\d`,",
    "//! `\\s` and `str.isdigit()` / `isupper()`, so that the Rust text processing treats every character as the",
    "//! Python does (Rust's own `\\w` differs: no `²`, but combining marks; its `\\s` lacks `\\x1c`-`\\x1f`).",
    "//! Do not edit: regenerate.",
    "",
]
for name, (doc, table) in tables.items():
    lines.append(f"/// {doc}")
    lines.append(f"pub const {name}: &[(u32, u32)] = &[")
    row = []
    for lo, hi in table:
        row.append(f"(0x{lo:X}, 0x{hi:X})")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    lines.append("")
lines.append("/// The zero of every run of ten decimal digits (`unicodedata.decimal`).")
lines.append("pub const DECIMAL_ZEROS: &[u32] = &[")
for i in range(0, len(zeros), 10):
    lines.append("    " + ", ".join(f"0x{z:X}" for z in zeros[i:i + 10]) + ",")
lines.append("];")
lines.append("")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
print("wrote", os.path.normpath(OUT))
